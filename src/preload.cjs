'use strict';

const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('omni', {
  state: () => ipcRenderer.invoke('state'),
  start: (key, kind, options) => ipcRenderer.invoke('start', key, kind, options),
  stop: (key, kind) => ipcRenderer.invoke('stop', key, kind),
  control: (key, kind, action, shade) => ipcRenderer.invoke('control', key, kind, action, shade),
  controlState: (key, kind) => ipcRenderer.invoke('control-state', key, kind),
  virtualInput: (key, kind, type, text) => ipcRenderer.invoke('virtual-input', key, kind, type, text),
  quickTiles: (key, kind) => ipcRenderer.invoke('quick-tiles', key, kind),
  clickQuickTile: (key, kind, component) => ipcRenderer.invoke('quick-tile-click', key, kind, component),
  info: (key, kind) => ipcRenderer.invoke('info', key, kind),
  photo: (key, useCatalog) => ipcRenderer.invoke('photo', key, useCatalog),
  pair: (address, code) => ipcRenderer.invoke('pair', address, code),
  connect: (address) => ipcRenderer.invoke('connect', address),
  save: (key, name, auto) => ipcRenderer.invoke('save', key, name, auto),
  forget: (key) => ipcRenderer.invoke('forget', key),
  reveal: () => ipcRenderer.invoke('reveal'),
  settings: (options) => ipcRenderer.invoke('settings', options),
  otg: (key) => ipcRenderer.invoke('otg', key),
  stopOtg: () => ipcRenderer.invoke('otg-stop'),
  wirelessScan: () => ipcRenderer.invoke('wireless-scan'),
  disconnect: (address) => ipcRenderer.invoke('disconnect', address),
  newQR: () => ipcRenderer.invoke('wireless-qr-new'),
  pollQR: (payload) => ipcRenderer.invoke('wireless-qr-poll', payload),
  terminalStart: (key, kind) => ipcRenderer.invoke('terminal-start', key, kind),
  terminalInput: (id, input) => ipcRenderer.invoke('terminal-input', id, input),
  terminalStop: (id) => ipcRenderer.invoke('terminal-stop', id),
  terminalData: (callback) => ipcRenderer.on('terminal-data', (_event, data) => callback(data)),
  adbHelp: () => ipcRenderer.invoke('adb-help'),
  adbRecipe: (key, kind, action) => ipcRenderer.invoke('adb-recipe', key, kind, action),
  adbScreenshot: (key, kind) => ipcRenderer.invoke('adb-screenshot', key, kind),
  onState: (callback) => ipcRenderer.on('state', (_event, data) => callback(data)),
  onNotice: (callback) => ipcRenderer.on('notice', (_event, data) => callback(data)),
});
